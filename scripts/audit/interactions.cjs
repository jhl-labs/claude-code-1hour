const {openBrowser}=require('@remotion/renderer');
const fs=require('node:fs');
(async()=>{
 const browser=await openBrowser('chrome',{browserExecutable:'/usr/bin/google-chrome'});
 const page=await browser.newPage({context:()=>null,logLevel:'error',indent:false,pageIndex:0,onBrowserLog:null,onLog:()=>{}});
 await page.setViewport({width:1440,height:1000,deviceScaleFactor:1});
 await page.goto({url:process.env.AUDIT_URL || 'http://localhost:3000',timeout:120000,options:{}});
 await page.evaluate(()=>document.fonts.ready);
 await page.evaluate(()=>new Promise((resolve,reject)=>{
  const deadline=Date.now()+15000;
  const check=()=>document.querySelector('nav [aria-current]') ? resolve(true) : Date.now()>deadline ? reject(new Error('Hydration timeout')) : setTimeout(check,50);
  check();
 }));
 const result=await page.evaluate(async()=>{
  const videos=[...document.querySelectorAll('video')];
  const initialPaused=videos.every(v=>v.paused);
  videos[0].textTracks[0].mode='hidden';
  const captionDeadline=Date.now()+5000;
  while(!videos[0].textTracks[0].cues?.length && Date.now()<captionDeadline) await new Promise(r=>setTimeout(r,50));
  const captionsLoad=videos[0].textTracks[0].cues?.length===4;
  await videos[0].play();
  await videos[1].play();
  const oneAtATime=videos[0].paused&&!videos[1].paused;
  videos[1].pause();
  const figure=videos[0].closest('figure');
  figure.querySelector('details').open=true;
  figure.querySelectorAll('button')[1].click();
  await new Promise(r=>setTimeout(r,200));
  const cueWorks=Math.abs(videos[0].currentTime-8)<0.15&&videos[0].paused;
  document.documentElement.style.scrollBehavior='auto';
  figure.scrollIntoView();
  await new Promise(r=>setTimeout(r,250));
  document.getElementById('hero').scrollIntoView();
  figure.scrollIntoView();
  await new Promise(r=>setTimeout(r,250));
  const staysPaused=videos.every(v=>v.paused);
  await videos[0].play();
  const animation=document.querySelector('[data-lesson-id="V1-timeline"]');
  animation.querySelector('button[aria-label="Play video"]').click();
  await new Promise(r=>setTimeout(r,200));
  const animationPausesMp4=videos[0].paused;
  await videos[1].play();
  await new Promise(r=>setTimeout(r,200));
  const mp4PausesAnimation=!!animation.querySelector('button[aria-label="Play video"]');
  videos[1].pause();
  return {captionsLoad,initialPaused,oneAtATime,cueWorks,staysPaused,animationPausesMp4,mp4PausesAnimation,controls:[...document.querySelectorAll('[data-lesson-id="V1-timeline"] button')].map(b=>({label:b.getAttribute('aria-label'),title:b.title}))};
 });
 fs.mkdirSync('.audit/after',{recursive:true});
 fs.writeFileSync('.audit/after/interactions.json',JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));
 await browser.close({silent:true});
 if(!result.captionsLoad||!result.initialPaused||!result.oneAtATime||!result.cueWorks||!result.staysPaused||!result.animationPausesMp4||!result.mp4PausesAnimation)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
